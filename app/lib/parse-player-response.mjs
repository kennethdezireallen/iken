/** Extract the assigned JSON object without treating string content as syntax. */
export function parsePlayerResponse(html) {
  const assignment = /\bytInitialPlayerResponse\s*=\s*\{/.exec(html);
  if (!assignment) return null;

  const start = assignment.index + assignment[0].length - 1;
  let depth = 0;
  let inString = false;
  let escaped = false;

  for (let index = start; index < html.length; index += 1) {
    const character = html[index];

    if (inString) {
      if (escaped) {
        escaped = false;
      } else if (character === '\\') {
        escaped = true;
      } else if (character === '"') {
        inString = false;
      }
      continue;
    }

    if (character === '"') {
      inString = true;
    } else if (character === '{') {
      depth += 1;
    } else if (character === '}') {
      depth -= 1;
      if (depth === 0) {
        try {
          return JSON.parse(html.slice(start, index + 1));
        } catch {
          return null;
        }
      }
    }
  }

  return null;
}
